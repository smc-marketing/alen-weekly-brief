"""Alen Security Weekly Google Ads Brief.

Workflow: compute ET windows -> read-only Google Ads pull (both weeks) ->
brief generated by a pinned Mistral model -> Telegram delivery.

READ-ONLY against the Google Ads account at all times.
"""
import asyncio
import datetime
import json
import os
import zoneinfo

import mistralai.workflows as workflows
from pydantic import BaseModel

from worker import ads_pull
from worker.brief_prompt import build_prompt
from worker.telegram_delivery import deliver_brief

ET = zoneinfo.ZoneInfo("America/New_York")


class AlenBriefInput(BaseModel):
    end: str | None = None      # default: yesterday ET
    start: str | None = None    # default: end - 6 days
    dry_run: bool = True        # True = build the brief but do NOT send to Telegram


@workflows.activity()
async def pull_data(windows: dict) -> dict:
    def run():
        client = ads_pull.build_client()
        ga = client.get_service("GoogleAdsService")
        return {
            "this": ads_pull.pull(ga, windows["start"], windows["end"]),
            "prev": ads_pull.pull(ga, windows["start_prev"], windows["end_prev"]),
        }

    return await asyncio.to_thread(run)


@workflows.activity()
async def generate_brief(prompt: str) -> str:
    from mistralai.client import Mistral

    client = Mistral()  # reads MISTRAL_API_KEY from the environment (platform-injected)
    model = os.environ.get("BRIEF_MODEL", "mistral-large-latest")  # pinned, never a default route
    messages = [{"role": "user", "content": prompt}]
    try:
        resp = await client.chat.async_.complete(model=model, messages=messages, temperature=0.2)
    except AttributeError:
        resp = client.chat.complete(model=model, messages=messages, temperature=0.2)
    return resp.choices[0].message.content


@workflows.activity()
async def send_brief(brief: str) -> dict:
    return await deliver_brief(brief)


@workflows.workflow.define(
    name="alen-weekly-brief",
    workflow_display_name="Alen Security Weekly Google Ads Brief",
    workflow_description=(
        "Read-only weekly Google Ads brief for Alen Security (Lens B, high-ticket "
        "B2B): pull, hard alerts, query hygiene, structure watch, next actions. "
        "Delivers to Telegram. Never mutates the account."
    ),
)
class AlenWeeklyBriefWorkflow:
    @workflows.workflow.entrypoint
    async def run(self, input: AlenBriefInput) -> dict:
        end_d = datetime.date.fromisoformat(input.end) if input.end \
            else (datetime.datetime.now(ET).date() - datetime.timedelta(days=1))
        start_d = datetime.date.fromisoformat(input.start) if input.start \
            else (end_d - datetime.timedelta(days=6))
        end_prev_d = start_d - datetime.timedelta(days=1)
        windows = {
            "start": start_d.isoformat(), "end": end_d.isoformat(),
            "start_prev": (end_prev_d - datetime.timedelta(days=6)).isoformat(),
            "end_prev": end_prev_d.isoformat(),
        }

        data = await pull_data(windows)
        brief = await generate_brief(build_prompt(data["this"], data["prev"]))

        result = {"windows": windows, "dry_run": input.dry_run, "brief": brief}
        if not input.dry_run:
            result["telegram"] = await send_brief(brief)
        return result
